def list_tasks() -> list[dict[str, Any]]:
    return [
        {
            "task_id": t["task_id"],
            "title": t["title"],
            "difficulty": t["difficulty"],
            "domain": t["domain"],
            "source_water": t["source_water"],
            "contaminants": t["contaminants"],
            "design_flow_m3_day": t["constraints"]["extra"]["design_flow_m3_day"],
            "max_lcow_usd_m3": t["constraints"]["extra"]["max_lcow_usd_m3"],
        }
        for t in BENCHMARK_TASKS
    ]


def get_task(task_id: str) -> dict[str, Any]:
    for t in BENCHMARK_TASKS:
        if t["task_id"] == task_id:
            return copy.deepcopy(t)
    raise ValueError(f"Unknown AquaDesignGym task_id: {task_id}")


def apply_influent_perturbation(task: dict[str, Any], profile: str = "nominal") -> dict[str, Any]:
    """Return a copy of a benchmark task with varying influent conditions applied."""
    if profile not in PERTURBATION_PROFILES:
        raise ValueError(f"Unknown perturbation profile: {profile}")
    out = copy.deepcopy(task)
    spec = PERTURBATION_PROFILES[profile]
    wq = out.setdefault("water_quality", {})
    for field_name, factor in spec["multipliers"].items():
        if field_name in wq and isinstance(wq[field_name], (int, float)) and not isinstance(wq[field_name], bool):
            wq[field_name] = round(float(wq[field_name]) * float(factor), 4)
    if "temperature_C" in wq and isinstance(wq["temperature_C"], (int, float)):
        wq["temperature_C"] = max(4.0, float(wq["temperature_C"]) + float(spec["temp_delta_C"]))
    out["perturbation_profile"] = profile
    return out
